#!/usr/bin/env node

/*!
 * build-tailwind-merge.mjs — generates dist/tailwind/merge.js, a
 * tailwind-merge (https://github.com/dcastil/tailwind-merge) `classGroups`
 * config so `extendTailwindMerge({ extend: { classGroups } })` resolves
 * conflicts between Chassis Tailwind utilities:
 *
 *   import { extendTailwindMerge } from 'tailwind-merge'
 *   import { classGroups } from '@chassis-ui/css/tailwind/merge.js'
 *   const twMerge = extendTailwindMerge({ extend: { classGroups } })
 *   twMerge('fg-primary', 'fg-danger') // -> 'fg-danger'
 *
 * Compiles `scss/tailwind/merge-manifest.scss` in isolation — it is not one
 * of the entries in build-tailwind.mjs's regular scss/tailwind/ pipeline —
 * and parses the `/* MERGE|<utility-map-key>|<class-name> *‍/` marker
 * comments it emits, one per generated utility class name, computed with
 * the SAME `utility-class-name()` function the real Tailwind emitter uses
 * (see `generate-tailwind-merge-manifest` in
 * scss/mixins/_utilities-tailwind.scss), so this can't drift from what
 * dist/tailwind/utilities.css actually contains. Group ids are the
 * utility map's own top-level keys (e.g. "fg-color", "margin"), unprefixed
 * by design: a Chassis group that happens to share a name with one of
 * tailwind-merge's own built-in groups (e.g. "opacity") extends that group
 * instead of creating a redundant separate one.
 *
 * Copyright 2026 Ozgur Gunes
 * Licensed under MIT (https://github.com/chassis-ui/css/blob/main/LICENSE)
 */

import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as sass from 'sass'

const root = path.resolve(fileURLToPath(import.meta.url), '../..')
const outDir = path.join(root, 'dist/tailwind')

const result = sass.compile(path.join(root, 'scss/tailwind/merge-manifest.scss'), {
  loadPaths: [path.join(root, 'scss/vendor'), path.join(root, 'node_modules')],
  style: 'expanded'
})

const classGroups = {}
const markerPattern = /\/\* MERGE\|([^|]+)\|([^*]+?) \*\//g
for (const match of result.css.matchAll(markerPattern)) {
  const [, group, className] = match
  ;(classGroups[group] ??= new Set()).add(className)
}

const sortedGroups = {}
for (const group of Object.keys(classGroups).sort()) {
  sortedGroups[group] = [...classGroups[group]].sort()
}

mkdirSync(outDir, { recursive: true })

const banner = `/*!
 * Chassis CSS — tailwind-merge classGroups config
 *
 * Generated by build/build-tailwind-merge.mjs from scss/tailwind/merge-manifest.scss.
 * Do not edit directly.
 *
 * Usage:
 *   import { extendTailwindMerge } from 'tailwind-merge'
 *   import { classGroups } from '@chassis-ui/css/tailwind/merge.js'
 *   const twMerge = extendTailwindMerge({ extend: { classGroups } })
 *   twMerge('fg-primary', 'fg-danger') // -> 'fg-danger'
 *
 * Group ids are Chassis's own utility map keys, unprefixed — a group that
 * shares a name with a built-in tailwind-merge group (e.g. "opacity")
 * extends it rather than creating a separate one. A few Chassis utilities
 * that share one underlying CSS property across multiple map keys (for
 * example base-shadow / elevation-shadow / shadow-color, which all set
 * box-shadow under the "shadow" class prefix) land in separate groups here
 * rather than one merged group — grouping is by map key, not by property.
 *
 * Copyright 2026 Ozgur Gunes
 * Licensed under MIT (https://github.com/chassis-ui/css/blob/main/LICENSE)
 */
`

writeFileSync(
  path.join(outDir, 'merge.js'),
  `${banner}\nexport const classGroups = ${JSON.stringify(sortedGroups, null, 2)}\n`
)
